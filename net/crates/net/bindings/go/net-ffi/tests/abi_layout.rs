fn fixture_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../../tests/c_abi/layout.json")
}

fn as_json(all: &[Measured]) -> serde_json::Value {
    let mut structs = BTreeMap::new();
    for m in all {
        let fields: Vec<serde_json::Value> = m
            .fields
            .iter()
            .map(|(c, r, off)| serde_json::json!([c, r, off]))
            .collect();
        structs.insert(
            m.c_name.to_string(),
            serde_json::json!({
                "rust": m.rust_path,
                "size": m.size,
                "align": m.align,
                "fields": fields,
            }),
        );
    }
    serde_json::json!({
        "comment": "rustc layout of every struct the C headers publish; written by \
                    bindings/go/net-ffi/tests/abi_layout.rs, compiled as C assertions by \
                    .github/scripts/check-c-abi.py",
        "structs": structs,
    })
}

#[test]
fn published_structs_have_the_fixture_layout() {
    let all = measured();
    assert!(!all.is_empty(), "the measure! table is empty");
    let measured = as_json(&all);
    let path = fixture_path();
    if std::env::var_os("NET_ABI_LAYOUT_WRITE").is_some() {
        let text = serde_json::to_string_pretty(&measured).expect("serialise") + "\n";
        std::fs::write(&path, text).expect("write the layout fixture");
        return;
    }
    let text =
        std::fs::read_to_string(&path).unwrap_or_else(|e| panic!("read {}: {e}", path.display()));
    let fixture: serde_json::Value = serde_json::from_str(&text).expect("parse the layout fixture");
    assert_eq!(
        fixture["structs"],
        measured["structs"],
        "rustc's layout differs from {}. If the change is intended, regenerate it with \
         NET_ABI_LAYOUT_WRITE=1 and review the diff; the C assertions in check-c-abi.py \
         then hold the headers to the same numbers.\nmeasured:\n{}",
        path.display(),
        serde_json::to_string_pretty(&measured["structs"]).unwrap_or_default()
    );
}
