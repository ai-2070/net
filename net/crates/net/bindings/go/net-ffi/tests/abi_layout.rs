//! Layout of every struct the C headers publish with a body, measured by
//! rustc and compared with the reviewed fixture
//! `net/crates/net/tests/c_abi/layout.json`.
//!
//! C SDK consumer verification, C1 check 4
//! (docs/internal/plans/C_SDK_CONSUMER_VERIFICATION_PLAN.md). The fixture is
//! where the two compilers meet: this test requires the Rust `#[repr(C)]`
//! structs to have exactly its size, alignment and field offsets, and
//! `.github/scripts/check-c-abi.py` compiles the same numbers as C
//! `_Static_assert`s against the shipped headers. Either side drifting fails
//! one of them.
//!
//! The table below is generated by
//! `check-c-abi.py --bundle <bundle> --emit-layout-table`, which pairs each C
//! struct with its Rust counterpart and the fields in order. The audit also
//! requires the fixture to cover every published struct, so a struct added to
//! a header without a row here fails there.
//!
//! To regenerate the fixture after an intended layout change:
//!
//! ```text
//! NET_ABI_LAYOUT_WRITE=1 cargo test --release -p net-ffi --test abi_layout
//! ```
//!
//! The fixture records a 64-bit target's sizes and offsets (pointers and
//! `size_t` are 8 bytes), the only width the C SDK is built and audited for,
//! so the test compiles only there: on a 32-bit target it would fail against
//! headers and code that are consistent, and regenerating would overwrite
//! the 64-bit fixture.
#![cfg(target_pointer_width = "64")]

use std::collections::BTreeMap;
use std::mem::{align_of, offset_of, size_of};
use std::path::PathBuf;

struct Measured {
    c_name: &'static str,
    rust_path: String,
    size: usize,
    align: usize,
    /// (C field, Rust field, offset)
    fields: Vec<(&'static str, &'static str, usize)>,
}

macro_rules! measure {
    ($c:literal => $ty:path { $($cf:literal : $rf:ident),* $(,)? }) => {
        Measured {
            c_name: $c,
            // `stringify!` of a path may space its `::` separators.
            rust_path: stringify!($ty).replace(' ', ""),
            size: size_of::<$ty>(),
            align: align_of::<$ty>(),
            fields: vec![$(($cf, stringify!($rf), offset_of!($ty, $rf))),*],
        }
    };
}

